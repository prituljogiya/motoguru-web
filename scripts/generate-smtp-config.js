#!/usr/bin/env node
/**
 * Reads EMAIL_* from .env / .env.local and writes public/api/smtp-config.php
 * for cPanel PHP SMTP deployments.
 */
const fs = require("fs");
const path = require("path");

function loadEnvFile(filePath) {
  if (!fs.existsSync(filePath)) return {};
  const out = {};
  for (const rawLine of fs.readFileSync(filePath, "utf8").split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    out[key] = value;
  }
  return out;
}

const root = path.join(__dirname, "..");
const env = {
  ...loadEnvFile(path.join(root, ".env")),
  ...loadEnvFile(path.join(root, ".env.local")),
  ...process.env,
};

const host = env.EMAIL_HOST || "mail.yourdomain.com";
const port = Number(env.EMAIL_PORT || 465);
const secure = (env.EMAIL_SECURE || (port === 465 ? "ssl" : "tls")).toLowerCase();
const user = env.EMAIL_USER || "noreply@yourdomain.com";
const pass = env.EMAIL_PASS || "CHANGE_ME";
const fromEmail = env.EMAIL_FROM || user;
const fromName = env.EMAIL_FROM_NAME || "Motoguru Website";
const toEmail = env.EMAIL_TO || user;

function phpString(value) {
  return `'${String(value).replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;
}

const php = `<?php
/**
 * Auto-generated by scripts/generate-smtp-config.js — do not commit secrets.
 */
return [
    'smtp_host' => ${phpString(host)},
    'smtp_port' => ${port},
    'smtp_secure' => ${phpString(secure === "true" ? "ssl" : secure)},
    'smtp_user' => ${phpString(user)},
    'smtp_pass' => ${phpString(pass)},
    'from_email' => ${phpString(fromEmail)},
    'from_name' => ${phpString(fromName)},
    'to_email' => ${phpString(toEmail)},
    'timeout' => 30,
];
`;

const outPath = path.join(root, "public", "api", "smtp-config.php");
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, php, "utf8");
console.log(`Wrote ${outPath}`);
